public class Student {
    private String id;
    private String name;
    private double gpa;

    public Student(String id, String name, double gpa) {
        this.id = id;
        this.name = name;
        this.gpa = gpa;
    }

    public String getInfo() {
        return id + " - " + name + " - GPA: " + gpa;
    }
}
